/** Escapes text for use inside HTML markup or a quoted attribute, for the
 *  places that hand Leaflet an HTML string (tooltips, div icons). */
export function escapeHtml(s: string): string {
  return s
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}
